// The metatable carries the members, so the __index closure takes it as its
// single upvalue and falls through to it. Both usertype forms are built with
// this function: sol2 set __name on every form it registered, and the name
// scripts see through tostring is the registry key itself.
void open_math_metatable(lua_State* L, const char* name, const luaL_Reg* methods, lua_CFunction index, lua_CFunction newindex) {
    luaL_newmetatable(L, name);
    luaL_setfuncs(L, methods, 0);

    lua_pushstring(L, name);
    lua_setfield(L, -2, "__name");

    lua_pushvalue(L, -1);
    lua_pushcclosure(L, index, 1);
    lua_setfield(L, -2, "__index");

    if (newindex != nullptr) {
        lua_pushcfunction(L, newindex);
        lua_setfield(L, -2, "__newindex");
    }

    lua_pop(L, 1);
}

// sol2 kept one metatable per usertype form with the same member set: the
// value form a constructor or an engine read produces, and the pointer form a
// matrix element is handed out as. Building the pointer form up front is what
// keeps sol2's lazy automatic registration -- an empty usertype under the same
// key -- from shadowing the members the first time m[0] is pushed.
template <typename T>
void open_math_type(lua_State* L, const luaL_Reg* methods, lua_CFunction index, lua_CFunction newindex) {
    open_math_metatable(L, math_metatable<T>(), methods, index, newindex);
    open_math_metatable(L, math_pointer_metatable<T>(), methods, index, newindex);
}

// sol2 published the metatable itself under the type name, so every member was
// reachable from the type table as well as from an instance. Keep that shape:
// the constructor and the field accessors live next to the methods.
template <typename T>
void open_math_type_table(lua_State* L, const char* metatable, lua_CFunction construct, const MathField<T>* fields, size_t count,
    const char* global) {
    luaL_getmetatable(L, metatable);

    lua_pushcfunction(L, construct);
    lua_setfield(L, -2, "new");

    for (size_t i = 0; i < count; ++i) {
        lua_pushlightuserdata(L, const_cast<MathField<T>*>(fields));
        lua_pushinteger(L, static_cast<lua_Integer>(i));
        lua_pushcclosure(L, &math_field_getter<T>, 2);
        lua_setfield(L, -2, fields[i].name);
    }

    lua_setglobal(L, global);
}

void open_math_usertypes(lua_State* L) {
    open_math_type<Vector2f>(L, VEC2_METHODS, vec2_index, vec2_newindex);
    open_math_type<Vector3f>(L, VEC3_METHODS, vec3_index, vec3_newindex);
    open_math_type<Vector4f>(L, VEC4_METHODS, vec4_index, vec4_newindex);
    open_math_type<Matrix4x4f>(L, MAT4_METHODS, mat4_index, mat4_newindex);
    open_math_type<glm::quat>(L, QUAT_METHODS, quat_index, quat_newindex);

    open_math_type_table(L, math_metatable<Vector2f>(), vec2_new, VEC2_FIELDS, std::size(VEC2_FIELDS), "Vector2f");
    open_math_type_table(L, math_metatable<Vector3f>(), vec3_new, VEC3_FIELDS, std::size(VEC3_FIELDS), "Vector3f");
    open_math_type_table(L, math_metatable<Vector4f>(), vec4_new, VEC4_FIELDS, std::size(VEC4_FIELDS), "Vector4f");
    open_math_type_table<Matrix4x4f>(L, math_metatable<Matrix4x4f>(), mat4_new, nullptr, 0, "Matrix4x4f");
    open_math_type_table(L, math_metatable<glm::quat>(), quat_new, QUAT_FIELDS, std::size(QUAT_FIELDS), "Quaternion");
}
