bool reframework_is_key_down(REFramework& framework, int key) {
    if (key < 0 || key >= 256) {
        return false;
    }

    return framework.get_keyboard_state()[key] != 0;
}

lua_stack::object reframework_get_first_key_down(lua_State* s, REFramework& framework) {
    const auto& states = framework.get_keyboard_state();

    for (int i = 0; i < 256; i++) {
        if (states[i] != 0) {
            return lua_stack::make_object(s, i);
        }
    }

    return lua_stack::make_object(s, lua_stack::lua_nil);
}

// The keyboard state is a fixed array, and sol2 pushed it as a container: an
// integer key is 1-based, the length is the array size, and pairs walks the
// elements. The state hands out a copy, so nothing writes back into the game.
using keyboard_state_t = std::array<uint8_t, 256>;

int keyboard_state_index(lua_State* L) {
    const auto* states = lua_stack::get_pointer<keyboard_state_t>(L, 1);

    if (states == nullptr || !lh::is_index(L, 2)) {
        lua_pushnil(L);
        return 1;
    }

    const int index = lh::index_int(L, 2);

    if (index < 1 || index > 256) {
        lua_pushnil(L);
        return 1;
    }

    lua_pushinteger(L, (*states)[index - 1]);
    return 1;
}

int keyboard_state_len(lua_State* L) {
    lua_pushinteger(L, 256);
    return 1;
}

int keyboard_state_next(lua_State* L) {
    const auto* states = lua_stack::get_pointer<keyboard_state_t>(L, 1);
    const int index = lh::is_none(L, 2) ? 1 : lh::index_int(L, 2) + 1;

    if (states == nullptr || index > 256) {
        lua_pushnil(L);
        return 1;
    }

    lua_pushinteger(L, index);
    lua_pushinteger(L, (*states)[index - 1]);
    return 2;
}

int keyboard_state_pairs(lua_State* L) {
    lua_pushcfunction(L, &keyboard_state_next);
    lua_pushvalue(L, 1);
    lua_pushnil(L);

    return 3;
}
