void ScriptRunner::on_frame() {
    // Serve RPC requests here: this thread owns the Lua state. Running it before
    // the scene checks below means a client gets "not ready" instead of the
    // timeout those early returns would otherwise cause.
    if (m_rpc) {
        const auto wanted_port = (uint16_t)m_rpc_port->value();

        if (m_rpc_enabled->value()) {
            if (m_rpc->is_running() && m_rpc->port() != wanted_port) {
                m_rpc->stop();
            }

            // Retry slowly so a port clash doesn't spam the log every frame.
            const auto now = std::chrono::steady_clock::now();

            if (!m_rpc->is_running() && now - m_rpc_last_start_attempt > std::chrono::seconds(5)) {
                m_rpc_last_start_attempt = now;
                m_rpc->start(wanted_port);
            }
        } else if (m_rpc->is_running()) {
            m_rpc->stop();
        }

        m_rpc->drain(*this);
    }

    if (!m_scene_okay) try {
        if (!m_checked_scene_once) {
            m_checked_scene_once = true;
            m_scene_check_time = std::chrono::system_clock::now();
        } else if (std::chrono::system_clock::now() - m_scene_check_time > std::chrono::seconds(5)) {
            m_scene_okay = true;
            spdlog::warn("[ScriptRunner] Scene or scene manager not found after 5 seconds. Loading scripts anyways...");
            return;
        } else {
            const auto scene_manager_t = sdk::find_type_definition("via.SceneManager");
            if (scene_manager_t == nullptr) {
                return;
            }

            const auto get_CurrentScene = scene_manager_t->get_method("get_CurrentScene");

            if (get_CurrentScene == nullptr) {
                return;
            }

            const auto scene_manager = sdk::get_native_singleton("via.SceneManager");

            if (scene_manager == nullptr) {
                return;
            }

            const auto context = sdk::get_thread_context();
            
            if (context == nullptr) {
                return;
            }
            
            const auto scene = get_CurrentScene->call_safe<void*>(context, scene_manager);

            if (scene == nullptr) {
                return;
            }

            m_scene_okay = true;
            spdlog::info("[ScriptRunner] Scene and scene manager found. Loading scripts...");
        }
    } catch (const std::exception& e) {
        spdlog::error("[ScriptRunner] Error while checking for scene: {}", e.what());
        return;
    } catch (...) {
        spdlog::error("[ScriptRunner] Unknown error while checking for scene.");
        return;
    }

    std::scoped_lock _{m_access_mutex};

    hook_battle_rule();

    if (m_needs_first_reset) {
        spdlog::info("[ScriptRunner] Initializing Lua state for the first time...");

        // Calling reset_scripts even though the scripts have never been set yet still works.
        reset_scripts();
        m_needs_first_reset = false;

        spdlog::info("[ScriptRunner] Lua state initialized.");
    }

    for (auto state_to_delete : m_states_to_delete) {
        std::erase_if(m_states, [&](const std::shared_ptr<ScriptState>& state) { return state->lua().lua_state() == state_to_delete; });
    }

    m_states_to_delete.clear();

    if (m_main_state == nullptr) {
        return;
    }

    if (!m_last_online_match_state) {
        for (auto &state : m_states) {
            state->on_frame();
        }

        // install_hooks gets called here because it ensures hooks get installed the next frame after they've been 
        // enqueued. This prevents a race that can occur if hooks were installed immediately during script loading.
        for (auto& state : m_states) {
            state->install_hooks();
        }
    }
}

void ScriptRunner::on_draw_ui() {
    ImGui::SetNextItemOpen(false, ImGuiCond_::ImGuiCond_Once);

    if (ImGui::CollapsingHeader(get_name().data())) {
        if (m_last_online_match_state) {
            ImGui::TextWrapped("Online match detected. Scripts will not be loaded. Existing scripts have been unloaded.");
            return;
        }

        if (ImGui::Button("Reset scripts")) {
            reset_scripts();
        }

        ImGui::SameLine();
        m_rpc_enabled->draw("Lua RPC");

        if (ImGui::IsItemHovered()) {
            ImGui::SetTooltip(
                "HTTP endpoint for running Lua in the game.\n"
                "POST http://127.0.0.1:%u/rpc with {\"code\": \"...\"} (\"mode\": \"chunk\"|\"expr\", \"timeout_ms\": 100-30000).\n"
                "Binds to 127.0.0.1 only. See docs/LUA_RPC.md.",
                (uint32_t)m_rpc_port->value());
        }

        if (m_rpc_enabled->value()) {
            ImGui::SameLine();
            ImGui::SetNextItemWidth(ImGui::CalcTextSize("00000").x + ImGui::GetStyle().FramePadding.x * 2.0f);
            m_rpc_port->draw("##Port");

            if (ImGui::IsItemHovered()) {
                ImGui::SetTooltip("Port");
            }

            if (m_rpc->is_running()) {
                ImGui::SameLine();
                ImGui::Text("reqs: %llu", (unsigned long long)m_rpc->served_requests());
            }
        }

        if (!m_rpc->is_running() && m_rpc_enabled->value()) {
            const auto rpc_error = m_rpc->last_error();
            if (!rpc_error.empty()) {
                ImGui::TextWrapped("Not listening: %s", rpc_error.c_str());
            }
        }

        ImGui::Separator();
        //Garbage collection currently only showing from main lua state, might rework to show total later?
        if (ImGui::TreeNode("Garbage Collection")) {
            std::scoped_lock _{ m_access_mutex };

            auto g = G(m_main_state->lua().lua_state());
            const auto bytes_in_use = g->totalbytes + g->GCdebt;

            ImGui::Text("Megabytes in use: %.2f", (float)bytes_in_use / 1024.0f / 1024.0f);

            if (m_gc_handler->draw("Handler")) {
                m_main_state->gc_data_changed(make_gc_data());
            }

            if (m_gc_mode->draw("Mode")) {
                m_main_state->gc_data_changed(make_gc_data());
            }

            if ((uint32_t)m_gc_mode->value() == (uint32_t)ScriptState::GarbageCollectionMode::GENERATIONAL) {
                if (m_gc_minor_multiplier->draw("Minor GC Multiplier")) {
                    m_main_state->gc_data_changed(make_gc_data());
                }

                if (m_gc_major_multiplier->draw("Major GC Multiplier")) {
                    m_main_state->gc_data_changed(make_gc_data());
                }
            }

            if (m_gc_handler->value() == (int32_t)ScriptState::GarbageCollectionHandler::REFRAMEWORK_MANAGED) {
                if (m_gc_type->draw("Type")) {
                    m_main_state->gc_data_changed(make_gc_data());
                }

                if ((uint32_t)m_gc_mode->value() != (uint32_t)ScriptState::GarbageCollectionMode::GENERATIONAL) {
                    if (m_gc_budget->draw("Budget")) {
                        m_main_state->gc_data_changed(make_gc_data());
                    }
                }
            }

            ImGui::TreePop();
        }

        m_log_to_disk->draw("Log Lua Errors to Disk");

        if (!m_last_script_error.empty()) {
            std::shared_lock _{m_script_error_mutex};

            const auto now = std::chrono::system_clock::now();
            const auto diff = now - m_last_script_error_time;
            const auto sec = std::chrono::duration<float>(diff).count();

            ImGui::TextWrapped("Last Error Time: %.2f seconds ago", sec);

            ImGui::PushStyleColor(ImGuiCol_Text, ImVec4(1.0f, 0.0f, 0.0f, 1.0f));
            ImGui::TextWrapped("Last Script Error: %s", m_last_script_error.data());
            ImGui::PopStyleColor();
        } else {
            ImGui::TextWrapped("No Script Errors... yet!");
        }

        if (!m_known_scripts.empty()) {
            ImGui::Text("Known scripts:");

            for (auto&& name : m_known_scripts) {
                if (ImGui::Checkbox(name.data(), &m_loaded_scripts_map[name])) {
                    reset_scripts();
                    break;
                }
            }
        } else {
            ImGui::Text("No scripts loaded.");
        }
    }

    if (!m_last_online_match_state) { 
        std::scoped_lock _{ m_access_mutex };

        ImGui::SetNextItemOpen(m_script_generated_ui_open_state->value(), ImGuiCond_Once);
        
        if (ImGui::CollapsingHeader("Script Generated UI")) {
            if (!m_script_generated_ui_open_state->value()) {
                m_script_generated_ui_open_state->value() = true;
                g_framework->request_save_config();
            }
            if (m_states.empty()) {
                return;
            }
            for (auto& state : m_states) {
                state->on_draw_ui();
            }
        } else {
            if (m_script_generated_ui_open_state->value()) {
                m_script_generated_ui_open_state->value() = false;
                g_framework->request_save_config();
            }
        }
    }
}

void ScriptRunner::on_update_transform(RETransform* transform) {
    if (!m_has_any_transform_updates) {
        return;
    }

    std::scoped_lock _{m_access_mutex};

    if (m_states.empty()) {
        return;
    }

    if (m_last_online_match_state) {
        return;
    }

    for (auto& state : m_states) {
        state->on_update_transform(transform);
    }
}

