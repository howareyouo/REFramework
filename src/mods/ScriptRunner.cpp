void ScriptState::install_hooks() {
    for (; !m_hooks_to_add.empty(); m_hooks_to_add.pop_front()) {
        auto hookdef = m_hooks_to_add.front();
        auto fn = hookdef.fn;
        auto callbacks = std::make_shared<HookCallbacks>(HookCallbacks{hookdef.pre_cb, hookdef.post_cb});
        auto ignore_jmp_object = hookdef.ignore_jmp_obj;
        const auto hookman_data = HookManager::EitherOr{hookdef.obj, hookdef.fn, ignore_jmp_object.is<bool>() ? ignore_jmp_object.as<bool>() : false};
        auto id = g_hookman.add_either_or(
            hookman_data,
            [callbacks, state = this, runner = ScriptRunner::get().get()](auto& args, auto& arg_tys, uintptr_t ret_addr) -> HookManager::PreHookResult {
                using PreHookResult = HookManager::PreHookResult;

                // Scripts are unloaded during online matches, so skip the lock and Lua entirely.
                if (runner->is_online_match()) {
                    return PreHookResult::CALL_ORIGINAL;
                }

                auto _ = state->scoped_lock();
                auto result = PreHookResult::CALL_ORIGINAL;

                // The state is being destroyed; its Lua references are gone.
                if (callbacks->released) {
                    return result;
                }

                auto& pre_cb = callbacks->pre_cb;

                try {
                    state->push_hook_storage(cached_thread_hash());

                    if (pre_cb.is_nil()) {
                        return result;
                    }

                    auto script_args_ref = state->get_table_pool().acquire(state->lua().lua_state());
                    lua_stack::table& script_args = script_args_ref;

                    // Call the script function.
                    // Convert the args to a table that we pass to the script function.
                    for (auto i = 0u; i < args.size(); ++i) {
                        script_args.set(static_cast<lua_Integer>(i + 1), (void*)args[i]);
                    }

                    auto script_result = pre_cb(script_args);

                    if (!script_result.valid()) {
                        lua_stack::script_default_on_error(state->lua().lua_state(), std::move(script_result));
                    }

                    auto script_result_obj = script_result.get<lua_stack::object>();

                    if (script_result_obj.is<PreHookResult>()) {
                        result = script_result_obj.as<PreHookResult>();
                    }

                    // Apply the changes to arguments that the script function may have made.
                    for (auto i = 0u; i < args.size(); ++i) {
                        auto arg = script_args.get<lua_stack::object>(static_cast<lua_Integer>(i + 1));
                        args[i] = (uintptr_t)arg.as<void*>();
                    }
                } catch (const std::exception& e) {
                    ScriptRunner::get()->spew_error(e.what());
                } catch (...) {
                    ScriptRunner::get()->spew_error("Unknown exception in pre_hook");
                }

                return result;
            },
            [callbacks, state = this, runner = ScriptRunner::get().get()](auto& ret_val, auto* ret_ty, uintptr_t ret_addr) {
                // Matches the pre-hook: nothing to pop when scripts are disabled mid-match.
                if (runner->is_online_match()) {
                    return;
                }

                auto _ = state->scoped_lock();

                // The state is being destroyed; its Lua references are gone.
                if (callbacks->released) {
                    return;
                }

                const auto thash = cached_thread_hash();
                utility::ScopeGuard sg{[state, thash] { state->pop_hook_storage(thash); }};

                try {
                    state->m_current_hook_storage = state->get_hook_storage_internal(thash);

                    auto& post_cb = callbacks->post_cb;

                    if (post_cb.is_nil()) {
                        return;
                    }

                    auto script_result = post_cb((void*)ret_val);

                    if (!script_result.valid()) {
                        lua_stack::script_default_on_error(state->lua().lua_state(), std::move(script_result));
                    }

                    ret_val = (uintptr_t)script_result.get<void*>();
                } catch (const std::exception& e) {
                    ScriptRunner::get()->spew_error(e.what());
                } catch (...) {
                    ScriptRunner::get()->spew_error("Unknown exception in post_hook");
                }
            }
        );
        m_hooks[fn].push_back({id, std::move(callbacks)});
    }
}

void ScriptState::add_delegate_callback(sdk::DelegateInvocation& invo, lua_stack::protected_function callback) {
    std::unique_lock _{s_delegates_mutex};
    auto it = s_delegates.find(invo.object);

    if (it != s_delegates.end()) {
        it->second->callbacks.add(callback);
    } else {
        auto storage = std::make_unique<DelegateStorage>();
        storage->owner = shared_from_this();
        storage->callbacks.add(callback);
        
        const auto system_object_t = sdk::find_type_definition("System.Object");

        if (system_object_t == nullptr) {
            return;
        }

        invo.object = (::REManagedObject*)system_object_t->create_instance_full();
        utility::re_managed_object::add_ref(invo.object);

        invo.func = &ScriptState::delegate_callback;
        s_delegates[invo.object] = std::move(storage);
    }
}

void ScriptState::delegate_callback(sdk::VMContext* ctx, REManagedObject* obj) {
    if (ctx == nullptr) {
        return;
    }

    std::scoped_lock _{ s_delegates_mutex };

    if (s_delegates.empty()) {
        return;
    }

    auto it = s_delegates.find(obj);

    if (it == s_delegates.end()) {
        return;
    }

    auto& delegate = it->second;
    auto owner_state = delegate->owner.lock();
    if (owner_state == nullptr) {
        s_delegates.erase(it);
        utility::re_managed_object::release(obj);
        return;
    }

    auto __ = owner_state->scoped_lock();

    delegate->callbacks.dispatch([&](lua_stack::protected_function& fn) {
        try {
            auto script_result = fn(obj);

            if (!script_result.valid()) {
                lua_stack::script_default_on_error(owner_state->lua().lua_state(), std::move(script_result));
            }
        } catch (const std::exception& e) {
            ScriptRunner::get()->spew_error(e.what());
        } catch(...) {
            ScriptRunner::get()->spew_error("Unknown error executing delegate callback");
        }

        return false;
    });
}

void ScriptState::gc_data_changed(GarbageCollectionData data) {
    // Handler
    switch (data.gc_handler) {
    case ScriptState::GarbageCollectionHandler::REFRAMEWORK_MANAGED:
        lua_gc(m_lua.lua_state(), LUA_GCSTOP);
        break;
    case ScriptState::GarbageCollectionHandler::LUA_MANAGED:
        lua_gc(m_lua.lua_state(), LUA_GCRESTART);
        break;
    default:
        lua_gc(m_lua.lua_state(), LUA_GCRESTART);
        data.gc_handler = ScriptState::GarbageCollectionHandler::LUA_MANAGED;
        break;
    }

    // Type 
    if (data.gc_type >= ScriptState::GarbageCollectionType::LAST) {
       data.gc_type = ScriptState::GarbageCollectionType::STEP;
    }

    // Mode
    if (data.gc_mode >= ScriptState::GarbageCollectionMode::LAST) {
        data.gc_mode = ScriptState::GarbageCollectionMode::GENERATIONAL;
    }

    switch (data.gc_mode) {
    case ScriptState::GarbageCollectionMode::GENERATIONAL:
        lua_gc(m_lua.lua_state(), LUA_GCGEN, data.gc_minor_multiplier, data.gc_major_multiplier);
        break;
    case ScriptState::GarbageCollectionMode::INCREMENTAL:
        lua_gc(m_lua.lua_state(), LUA_GCINC);
        break;
    default:
        lua_gc(m_lua.lua_state(), LUA_GCGEN, data.gc_minor_multiplier, data.gc_major_multiplier);
        data.gc_mode = ScriptState::GarbageCollectionMode::GENERATIONAL;
        break;
    }

    m_gc_data = data;
}

