void ScriptState::on_pre_application_entry(size_t hash) {
    if (m_pre_application_entry_fns.empty()) {
        return;
    }

    auto range = m_pre_application_entry_fns.equal_range(hash);

    if (range.first == range.second) {
        return;
    }

    run_guarded(m_execution_mutex, "Unknown exception in on_pre_application_entry", [&range, this] {
        for (auto it = range.first; it != range.second; ++it) {
            handle_protected_result(it->second());
        }
    });
}

void ScriptState::on_application_entry(size_t hash) {
    if (!m_application_entry_fns.empty()) {
        auto range = m_application_entry_fns.equal_range(hash);

        if (range.first != range.second) {
            run_guarded(m_execution_mutex, "Unknown exception in on_application_entry", [&range, this] {
                for (auto it = range.first; it != range.second; ++it) {
                    handle_protected_result(it->second());
                }
            });
        }
    }

    if (hash == "EndRendering"_fnv && m_gc_data.gc_handler == ScriptState::GarbageCollectionHandler::REFRAMEWORK_MANAGED) {
        std::scoped_lock _{ m_execution_mutex };

        // Sometimes this gets re-enabled? Not sure why.
        lua_gc(m_lua.lua_state(), LUA_GCSTOP);

        switch (m_gc_data.gc_type) {
            case ScriptState::GarbageCollectionType::FULL:
                lua_gc(m_lua.lua_state(), LUA_GCCOLLECT);
                break;
            case ScriptState::GarbageCollectionType::STEP:
                {
                    const auto now = std::chrono::high_resolution_clock::now();

                    if (m_gc_data.gc_mode == ScriptState::GarbageCollectionMode::GENERATIONAL) {
                        lua_gc(m_lua.lua_state(), LUA_GCSTEP, 1);
                    } else {
                        while (lua_gc(m_lua.lua_state(), LUA_GCSTEP, 1) == 0) {
                            if (std::chrono::high_resolution_clock::now() - now >= m_gc_data.gc_budget) {
                                break;
                            }
                        }
                    }
                }
                break;
            default:
                lua_gc(m_lua.lua_state(), LUA_GCCOLLECT);
                break;
        };
    }
}

bool ScriptState::on_pre_gui_draw_element(REComponent* gui_element, void* context) {
    if (m_pre_gui_draw_element_fns.empty()) {
        return true;
    }

    bool any_false = false;

    run_guarded(m_execution_mutex, "Unknown exception in on_pre_gui_draw_element", [&] {
        m_pre_gui_draw_element_fns.dispatch([&](lua_stack::protected_function& fn) {
            auto result = handle_protected_result(fn(gui_element, context));

            if (lua_stack::object result_obj = result.get<lua_stack::object>(); !result_obj.is<lua_stack::nil_t>() && result_obj.is<bool>() && result_obj.as<bool>() == false) {
                any_false = true;
                return false;
            }

            return should_remove_hook(result);
        });
    });

    return !any_false;
}

